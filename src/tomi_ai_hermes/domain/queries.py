def candidate_query(question: str) -> str:
    aliases = {
        "schiffbau": "shipbuilding",
        "construcción naval": "shipbuilding",
        "construction navale": "shipbuilding",
        "blanchiment": "bleaching",
        "bleichen": "bleaching",
        "blanqueo": "bleaching",
        "poids et mesures": "weights measures",
        "gewichte": "weights",
    }
    query = question.casefold()
    for source, target in aliases.items():
        query = query.replace(source, target)
    words = [word for word in re.findall(r"[^\W\d_]+", query) if word not in STOPWORDS]
    return " ".join(dict.fromkeys(words))[:512] or " ".join(question.split()[:64])[:512]
